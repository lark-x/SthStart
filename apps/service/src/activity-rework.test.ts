test('applying a creation profile updates content and image settings together with version checks', async (t) => {
    const { createService } = await import('./server.js');
    const { readConfig } = await import('./config.js');
    const db = new ServiceDatabase();
    const store = new ActivityStore(db);
    const token = 'rework-profile-test-token-123456789';
    const { app } = await createService({ database: db, config: readConfig({ STHSTART_ADMIN_TOKEN: token }), secrets: new SecretStore({}) });
    t.after(async () => { await app.close(); db.close(); });
    const doc = fixture();
    const { activity, draft } = store.createActivity({ title: doc.activity.title, type: doc.activity.type, initialDocument: doc });
    const preset = createActivityPreset(db, { kind: 'creation_profile', name: '水彩', payload: { textMode: 'whole-text', candidateCount: 2, globalStylePrompt: 'watercolor' } });
    const path = `/api/v1/admin/activities/${activity.id}/creation-profile/apply`;
    const headers = { 'x-sthstart-admin-token': token };
    const response = await app.inject({ method: 'POST', url: path, headers, payload: { presetId: preset.id, presetVersion: preset.version, expectedHeadVersion: activity.headVersion, expectedDraftVersion: draft.draftVersion } });
    assert.equal(response.statusCode, 200, response.body);
    assert.equal(getImageConfigDraft(db, activity.id).document.globalStylePrompt, 'watercolor');
    assert.deepEqual(store.getDraft(activity.id)!.document.messages, doc.messages);
    assert.equal((store.getDraft(activity.id)!.document.activity.creationProfile!.values as {
        textMode: string;
    }).textMode, 'whole-text');
    const head = store.getActivity(activity.id)!.headVersion;
    updateActivityPreset(db, preset.id, { name: '新版水彩' });
    const stale = await app.inject({ method: 'POST', url: path, headers, payload: { presetId: preset.id, presetVersion: preset.version, expectedHeadVersion: head, expectedDraftVersion: store.getDraft(activity.id)!.draftVersion } });
    assert.equal(stale.statusCode, 409);
    assert.equal(store.getActivity(activity.id)!.headVersion, head);
    const cleared = await app.inject({ method: 'POST', url: path, headers, payload: { presetId: null, presetVersion: 0, expectedHeadVersion: head, expectedDraftVersion: store.getDraft(activity.id)!.draftVersion } });
    assert.equal(cleared.statusCode, 200, cleared.body);
    assert.equal(store.getDraft(activity.id)!.document.activity.creationProfile, undefined);
});
