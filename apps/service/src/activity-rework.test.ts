test('project import remaps frozen roles and restores partial candidate progress without restarting jobs', async (t) => {
    const { mkdtempSync, rmSync } = await import('node:fs');
    const { tmpdir } = await import('node:os');
    const { join } = await import('node:path');
    const { readConfig } = await import('./config.js');
    const { buildActivityExportPackage } = await import('./activities/exports.js');
    const { stageActivityImport, commitActivityImport } = await import('./activities/imports.js');
    const root = mkdtempSync(join(tmpdir(), 'rework-roundtrip-'));
    t.after(() => rmSync(root, { recursive: true, force: true }));
    const config = readConfig({ STHSTART_ARTIFACT_DIR: root });
    config.artifactDirectory = root;
    const { db, store, doc, id } = setup(t);
    doc.activity.templateSnapshot = { presetId: 'deleted-template', name: '双人模板', version: 1, payload: { roleSlots: [{ id: 'lead', label: '寿星' }] }, actorMappings: { lead: ['a'] } };
    doc.activity.birthdayActorIds = ['a'];
    doc.activity.creationProfile = { name: '旧配置', version: 2, values: normalizeCreationProfile({ candidateCount: 3 }) };
    commit(store, id, doc);
    const candidate = store.createCandidate({ activityId: id, scope: { mode: 'rewrite-records', recordIds: ['m1', 'm2'], reviewBaseline: rewriteBaseline(doc, { recordIds: ['m1', 'm2'] }) }, payload: { rewrittenMessages: [{ id: 'm1', text: '已采用内容' }, { id: 'm2', text: '待采用内容' }] }, validation: {} });
    applyCandidateSelection(db, store, id, candidate.id, { unitIds: ['rewrite_message:m1'], idempotencyKey: 'export1', expectedHeadVersion: store.getActivity(id)!.headVersion, expectedDraftVersion: store.getDraft(id)!.draftVersion });
    const bytes = await buildActivityExportPackage(config, db, store, id, { format: 'project' });
    const staged = await stageActivityImport(config, db, bytes);
    const imported = await commitActivityImport(config, db, store, staged.jobId);
    const fresh = store.getDraft(imported.activity.id)!.document;
    assert.notEqual(fresh.actors[0].id, 'a');
    assert.deepEqual(fresh.activity.templateSnapshot!.actorMappings!.lead, [fresh.actors[0].id]);
    assert.deepEqual(fresh.activity.birthdayActorIds, [fresh.actors[0].id]);
    assert.equal((fresh.activity.creationProfile!.values as {
        candidateCount: number;
    }).candidateCount, 3);
    const newCandidate = store.listCandidates(imported.activity.id)[0];
    const comparison = compareCandidate(db, store, imported.activity.id, newCandidate.id);
    assert.equal(comparison.units.filter(u => u.applied).length, 1);
    assert.equal(comparison.units.filter(u => !u.applied && !u.conflict).length, 1);
    const remaining = comparison.units.find(u => !u.applied)!;
    applyCandidateSelection(db, store, imported.activity.id, newCandidate.id, { unitIds: [remaining.id], idempotencyKey: 'import1', expectedHeadVersion: 1, expectedDraftVersion: 1 });
    assert.equal(store.getDraft(imported.activity.id)!.document.messages[1].text, '待采用内容');
    assert.equal(db.connection.prepare("SELECT COUNT(*) n FROM activity_jobs WHERE activity_id=? AND status IN ('queued','running')").get(imported.activity.id)!.n, 0);
});
test('later candidates require their exact adopted predecessors', async (t) => {
    const { assertCandidateDependencies, recordWholeApplication } = await import('./activities/candidate-review.js');
    const { db, store, doc, id } = setup(t);
    const first = store.createCandidate({ activityId: id, scope: { mode: 'stage', stageId: doc.stages[0].id }, payload: {}, validation: {} });
    const later = store.createCandidate({ activityId: id, scope: { mode: 'stage', stageId: doc.stages[1].id, precedingCandidateIds: [first.id] }, payload: {}, validation: {} });
    assert.throws(() => assertCandidateDependencies(db, store, id, later.id), /前序/);
    assert.doesNotThrow(() => assertCandidateDependencies(db, store, id, later.id, [first.id, later.id]));
    db.connection.prepare('UPDATE activity_candidates SET adopted=1 WHERE id=?').run(first.id);
    recordWholeApplication(db, id, first.id, doc, doc.stages[0].id, store.getActivity(id)!.currentContentRevisionId!);
    assert.doesNotThrow(() => assertCandidateDependencies(db, store, id, later.id));
    doc.messages[0].text = '改过的前序';
    commit(store, id, doc);
    assert.throws(() => assertCandidateDependencies(db, store, id, later.id), /又发生了变化/);
});
