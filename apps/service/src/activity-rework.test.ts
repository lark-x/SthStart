test('review decisions persist, new changes resurface, deferred images never submit', async (t) => {
    const { db, store, doc, id } = setup(t);
    doc.actors[0].outfitDescription = '礼服';
    commit(store, id, doc);
    let item = listReviewItems(db, store, id).find(i => i.targetKind === 'image')!;
    assert.ok(item);
    decideReviewItems(db, store, id, { items: [item], decision: 'keep', expectedHeadVersion: store.getActivity(id)!.headVersion });
    commit(store, id, doc);
    assert.equal(listReviewItems(db, store, id).filter(i => i.decision === 'pending').length, 0);
    doc.actors[0].outfitDescription = '泳装';
    commit(store, id, doc);
    item = listReviewItems(db, store, id).find(i => i.targetKind === 'image' && i.decision === 'pending')!;
    assert.ok(item);
    decideReviewItems(db, store, id, { items: [item], decision: 'rework', expectedHeadVersion: store.getActivity(id)!.headVersion });
    let calls = 0;
    const fetcher: typeof fetch = async () => { calls++; throw new Error('must not connect'); };
    const result = await startReviewItems(db, new SecretStore({}), store, id, { ids: [item.id] }, fetcher);
    assert.equal(calls, 0);
    assert.match(result.results[0].message!, /图片/);
    assert.equal(listReviewItems(db, store, id).find(i => i.id === item.id)!.decision, 'rework');
});
test('partial adoption preserves identity and media; remaining items stay available; retry is idempotent', t => {
    const { db, store, doc, id } = setup(t);
    const candidate = store.createCandidate({ activityId: id, scope: { mode: 'rewrite-records', recordIds: ['m1', 'm2', 'm3'], reviewBaseline: rewriteBaseline(doc, { recordIds: ['m1', 'm2', 'm3'] }) }, payload: { rewrittenMessages: [1, 2, 3].map(n => ({ id: `m${n}`, text: `新消息 ${n}` })) }, validation: {} });
    const apply = (unitIds: string[], key: string) => applyCandidateSelection(db, store, id, candidate.id, { unitIds, idempotencyKey: key, expectedHeadVersion: store.getActivity(id)!.headVersion, expectedDraftVersion: store.getDraft(id)!.draftVersion });
    apply(['rewrite_message:m1', 'rewrite_message:m2'], 'request1');
    assert.deepEqual(store.getDraft(id)!.document.messages[0].mediaSlotIds, ['image']);
    assert.equal(store.getDraft(id)!.document.messages[2].text, '消息 3');
    assert.equal(compareCandidate(db, store, id, candidate.id).units.filter(u => !u.applied && !u.conflict).length, 1);
    const head = store.getActivity(id)!.headVersion;
    apply(['rewrite_message:m1', 'rewrite_message:m2'], 'request1');
    assert.equal(store.getActivity(id)!.headVersion, head);
    assert.throws(() => apply(['rewrite_message:m3'], 'request1'), /相同请求/);
    apply(['rewrite_message:m3'], 'request2');
    assert.ok(store.getCandidate(id, candidate.id)!.adopted);
    assert.equal(store.getDraft(id)!.document.messages[2].text, '新消息 3');
    assert.equal((store.getCandidate(id, candidate.id)!.payload.rewrittenMessages as unknown[]).length, 3);
});
