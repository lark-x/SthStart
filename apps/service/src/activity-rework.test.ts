function commit(store: ActivityStore, id: string, doc: ContentDocument) { const draft = store.updateDraft(id, store.getDraft(id)!.draftVersion, doc); return store.commitDraft(id, store.getActivity(id)!.headVersion, draft.draftVersion); }
